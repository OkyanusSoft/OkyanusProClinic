/* ============================================================
   الكود — أضفه في function Workstation بعد تعريف prevSession
   ============================================================ */

// النسخ التلقائي لبيانات الجلسة السابقة عند بدء جلسة من عودة
useEffect(() => {
  if (session.fromFuId && prevSession && session.procedures.length === 0) {
    // انسخ كل الإجراءات مع معرفات جديدة
    const copiedProcs = prevSession.procedures.map((proc) => ({
      ...proc,
      id: uid(),
      stageId: session.stages[session.stages.length - 1]?.id,
    }));

    // انسخ التشخيص والفحص والأدوية
    patch({
      procedures: copiedProcs,
      diagnosis: prevSession.diagnosis || session.diagnosis,
      examination: prevSession.examination || ئ.examination,
      meds: prevSession.meds ? [...prevSession.meds] : session.meds,
    });
  }
}, [session.fromFuId, prevSession?.id, session.id]);


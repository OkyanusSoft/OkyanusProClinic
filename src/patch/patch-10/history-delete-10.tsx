import { useStore } from "../store";
import { TwoStepDelete, useToast } from "../components/ui";

function SessionDeleteBtn({ sessionId, patientName }: { sessionId: string; patientName?: string }) {
  const { dispatch } = useStore();
  const { push } = useToast();

  return (
    <TwoStepDelete
      label="حذف الجلسة"
      onConfirm={() => {
        dispatch({ type: "DELETE_SESSION", id: sessionId });
        // البصمة تُضاف تلقائيًا عبر موزّع dispatch (الخطوة ١) → لن تعود أبدًا
        push("warn", "حُذفت الجلسة نهائيًا", patientName ? `جلسة ${patientName} أُزيلت من كل الأجهزة.` : "لن تظهر هذه الجلسة مجددًا على أي جهاز.");
      }}
    />
  );
}

export { SessionDeleteBtn };

